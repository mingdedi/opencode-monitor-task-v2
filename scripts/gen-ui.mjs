// 看板资产生成：packages/server/src/ui.html → packages/server/src/ui-html.ts
//
// 单文件看板以 JSON.stringify 字符串字面量形式进入 TS 模块——tsx 源码形态与 esbuild
// bundle 形态共用同一 import，零 loader 魔法，单文件发布形态（dist/server.mjs）不破。
// ui.html 是唯一编辑入口；ui-html.ts 是生成物（提交入库，fresh clone 源码直跑可用）。
// 漂移门禁：test/ui-asset.test.ts 断言生成物与 ui.html 逐字节一致（npm test 把关）。
//
// 用法: node scripts/gen-ui.mjs   （npm run build 亦自动先跑）

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function genUi() {
  const src = path.join(ROOT, "packages", "server", "src", "ui.html");
  const dst = path.join(ROOT, "packages", "server", "src", "ui-html.ts");
  const html = readFileSync(src, "utf8");
  const content =
    `// Generated by scripts/gen-ui.mjs — DO NOT EDIT. Source: packages/server/src/ui.html\n` +
    `export default ${JSON.stringify(html)};\n`;
  writeFileSync(dst, content);
  return { bytes: html.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = genUi();
  console.log(`ui-html.ts generated (${(r.bytes / 1024).toFixed(1)} KiB html embedded)`);
}
